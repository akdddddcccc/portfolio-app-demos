const STOP_TOKENS = new Set(["什么", "怎么", "如何", "可以", "一下", "这个", "那个", "有没有", "知道", "告诉", "觉得", "我们", "你们", "他们"]);

function queryTokens(query) {
  const normalized = String(query || "").toLowerCase().replace(/[^\p{L}\p{N}]+/gu, "");
  const tokens = new Set();
  const latinWords = String(query || "").toLowerCase().match(/[a-z0-9][a-z0-9._-]{1,}/g) || [];
  latinWords.forEach((word) => tokens.add(word));
  for (const size of [2, 3, 4]) {
    for (let index = 0; index <= normalized.length - size; index += 1) {
      const token = normalized.slice(index, index + size);
      if (!STOP_TOKENS.has(token)) tokens.add(token);
    }
  }
  return [...tokens];
}

export function buildCuratedKnowledgeContext(query, limit = 6) {
  const tokens = queryTokens(query);
  const ranked = ENTRIES.map((entry) => {
    const haystack = `${entry.title} ${entry.tags} ${entry.content}`.toLowerCase();
    let score = 0;
    tokens.forEach((token) => {
      if (haystack.includes(token)) score += token.length * token.length;
      if (entry.tags.toLowerCase().includes(token)) score += token.length * 2;
    });
    return { entry, score };
  }).sort((a, b) => b.score - a.score);

  const selected = ranked.filter((item) => item.score > 0).slice(0, limit);
  if (!selected.length) selected.push(...ranked.filter(({ entry }) => ["school-overview", "yuanbai-history"].includes(entry.id)));
  return selected.map(({ entry }) => (
    `[${entry.kind}｜${entry.title}]\n${entry.content}\n来源：${entry.source}`
  )).join("\n\n");
}

